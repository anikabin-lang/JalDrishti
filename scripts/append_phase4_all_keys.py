def main():
    with open('frontend/src/i18n/translations.ts', 'r', encoding='utf-8') as f:
        content = f.read()

    langs = ['en', 'hi', 'bn', 'te', 'mr', 'ta', 'ur', 'gu', 'kn', 'ml', 'or', 'pa', 'as', 'ks', 'sa']

    for lang in langs:
        data = NEW_KEYS[lang]
        # find the end of this lang block:
        # It begins with '"{lang}": {'
        lang_start = content.find(f'"{lang}": {{')
        if lang_start == -1:
            print(f'Warning: {lang} not found!')
            continue
        
        # We want to insert before the closing brace of this language
        # To find the matching closing brace, look for the next language or end
        next_indices = [content.find(f'"{l}": {{', lang_start + 1) for l in langs if content.find(f'"{l}": {{', lang_start + 1) != -1]
        if next_indices:
            end_search = min(next_indices)
            close_brace = content.rfind('},', lang_start, end_search)
        else:
            close_brace = content.find('}\n};', lang_start)
            if close_brace == -1:
                close_brace = content.find('}\n  };', lang_start)

        # Build entries to insert
        lines = []
        for k, v in data.items():
            escaped_v = v.replace('"', '\\"').replace('\n', ' ')
            lines.append(f'    "{k}": "{escaped_v}",')
        inserted_text = "\n" + "\n".join(lines) + "\n  "

        content = content[:close_brace] + inserted_text + content[close_brace:]

    with open('frontend/src/i18n/translations.ts', 'w', encoding='utf-8') as f:
        f.write(content)

    print("Successfully appended Phase 4 keys to all 15 languages!")

if __name__ == '__main__':
    main()

