# -*- coding: utf-8 -*-
"""Compiles all 15 languages and generates frontend/src/i18n/translations.ts."""
import json
import os
import sys

# Ensure current directory is in path
sys.path.insert(0, os.path.dirname(__file__))

from translation_data_rest import TRANSLATIONS_ALL
from append_phase3_keys import PHASE3_KEYS

LANG_METADATA = [
    {"code": "en", "name": "English", "nativeName": "English"},
    {"code": "hi", "name": "Hindi", "nativeName": "हिन्दी"},
    {"code": "bn", "name": "Bengali", "nativeName": "বাংলা"},
    {"code": "te", "name": "Telugu", "nativeName": "తెలుగు"},
    {"code": "mr", "name": "Marathi", "nativeName": "मराठी"},
    {"code": "ta", "name": "Tamil", "nativeName": "தமிழ்"},
    {"code": "ur", "name": "Urdu", "nativeName": "اردو", "isRtl": True},
    {"code": "gu", "name": "Gujarati", "nativeName": "ગુજરાતી"},
    {"code": "kn", "name": "Kannada", "nativeName": "ಕನ್ನಡ"},
    {"code": "ml", "name": "Malayalam", "nativeName": "മലയാളം"},
    {"code": "or", "name": "Odia", "nativeName": "ଓଡ଼ିଆ"},
    {"code": "pa", "name": "Punjabi", "nativeName": "ਪੰਜਾਬੀ"},
    {"code": "as", "name": "Assamese", "nativeName": "অসমীয়া"},
    {"code": "ks", "name": "Kashmiri", "nativeName": "کٲشُر", "isRtl": True},
    {"code": "sa", "name": "Sanskrit", "nativeName": "संस्कृतम्"},
]

def generate():
    target_path = os.path.abspath(os.path.join(os.path.dirname(__file__), "../frontend/src/i18n/translations.ts"))
    
    # Merge Phase 3 keys into TRANSLATIONS_ALL
    for code, extra in PHASE3_KEYS.items():
        if code in TRANSLATIONS_ALL:
            TRANSLATIONS_ALL[code].update(extra)

    # Check that all keys in 'en' are present in all languages, or fill them from 'en'
    en_keys = set(TRANSLATIONS_ALL["en"].keys())
    for code, dict_data in TRANSLATIONS_ALL.items():
        missing = en_keys - set(dict_data.keys())
        if missing:
            print(f"Warning: {code} has {len(missing)} missing keys. Filling with fallback.")
            for k in missing:
                dict_data[k] = TRANSLATIONS_ALL["en"][k]

    content = f"""/**
 * Complete 15-Language Translation Registry for JalDrishti Enterprise Heritage AI.
 * 
 * Auto-generated by scripts/generate_complete_translations.py
 * Total languages: {len(TRANSLATIONS_ALL)}
 * Total keys per language: {len(en_keys)}
 */

export interface LanguageOption {{
  code: string;
  name: string;
  nativeName: string;
  isRtl?: boolean;
}}

export const SUPPORTED_LANGUAGES: LanguageOption[] = {json.dumps(LANG_METADATA, indent=2, ensure_ascii=False)};

export const TRANSLATIONS: Record<string, Record<string, string>> = {json.dumps(TRANSLATIONS_ALL, indent=2, ensure_ascii=False)};
"""
    with open(target_path, "w", encoding="utf-8") as f:
        f.write(content)
    
    print(f"Successfully generated {target_path} ({len(TRANSLATIONS_ALL)} languages, {len(en_keys)} keys each).")

if __name__ == "__main__":
    generate()
